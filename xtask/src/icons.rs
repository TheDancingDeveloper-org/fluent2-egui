//! Download the Fluent System Icons subset and write `fluent2-icons` generated.rs.

use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;

const REV: &str = "64e5aa757d1b70c24a283256ddcb8269d0f58773";
const SIZES: &[u32] = &[16, 20, 24];
const STYLES: &[&str] = &["regular", "filled"];
const HEADER: &str = "// @generated by cargo xtask gen-icons — do not edit\n";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..")
}

struct Icon {
    folder: String,
    variant: String,
    snake: String,
}

pub fn generate(refresh: bool) -> Result<(), String> {
    generate_with(refresh, true)
}

/// Rebuild the committed catalogue from `icons.txt` and the committed SVGs.
///
/// `fetch` is what `gen-icons` uses: missing files are downloaded from the pinned
/// Fluent System Icons revision. The drift check passes `false`, so a missing or
/// stale committed SVG fails instead of touching the network.
pub fn generate_with(refresh: bool, allow_fetch: bool) -> Result<(), String> {
    let root = repo_root();
    let list_path = root.join("crates/fluent2-icons/icons.txt");
    let svg_dir = root.join("crates/fluent2-icons/svg");
    fs::create_dir_all(&svg_dir).map_err(|e| e.to_string())?;

    let raw = fs::read_to_string(&list_path).map_err(|e| format!("{list_path:?}: {e}"))?;
    let folders: Vec<String> = raw
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_string)
        .collect();
    if folders.is_empty() {
        return Err("icons.txt is empty".to_string());
    }
    let mut sorted = folders.clone();
    sorted.sort();
    if folders != sorted {
        return Err("icons.txt must be sorted".to_string());
    }

    let icons: Vec<Icon> = folders
        .iter()
        .map(|folder| Icon {
            folder: folder.clone(),
            variant: pascal(folder),
            snake: snake(folder),
        })
        .collect();

    let agent: ureq::Agent = ureq::Agent::config_builder()
        .timeout_global(Some(Duration::from_secs(60)))
        .build()
        .into();

    let mut missing: Vec<String> = Vec::new();
    for icon in &icons {
        for size in SIZES {
            for style in STYLES {
                let file = format!("ic_fluent_{}_{size}_{style}.svg", icon.snake);
                let dest = svg_dir.join(&file);
                if dest.exists() && !refresh {
                    continue;
                }
                if !allow_fetch {
                    return Err(format!(
                        "{file}: committed SVG missing; run cargo xtask gen-icons (network)"
                    ));
                }
                let folder_enc = icon.folder.replace(' ', "%20");
                let url = format!(
                    "https://raw.githubusercontent.com/microsoft/fluentui-system-icons/{REV}/assets/{folder_enc}/SVG/{file}"
                );
                match fetch(&agent, &url) {
                    Ok(bytes) => {
                        if !bytes.starts_with(b"<svg") && !bytes.starts_with(b"<?xml") {
                            return Err(format!("{file}: response is not SVG"));
                        }
                        fs::write(&dest, bytes).map_err(|e| format!("{dest:?}: {e}"))?;
                    }
                    Err(FetchErr::Status(404)) => {
                        if dest.exists() {
                            fs::remove_file(&dest).map_err(|e| e.to_string())?;
                        }
                        missing.push(format!("{}::{size}::{style}", icon.variant));
                    }
                    Err(other) => return Err(format!("{file}: {other}")),
                }
            }
        }
    }
    missing.sort();

    let generated = render(&icons, &svg_dir, &missing)?;
    let out = root.join("crates/fluent2-icons/src/generated.rs");
    fs::write(&out, generated).map_err(|e| format!("{out:?}: {e}"))?;
    rustfmt(&out)?;
    eprintln!(
        "gen-icons: {} icons, {} missing size/style combos",
        icons.len(),
        missing.len()
    );
    Ok(())
}

enum FetchErr {
    Status(u16),
    Other(String),
}

impl std::fmt::Display for FetchErr {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            FetchErr::Status(code) => write!(f, "HTTP {code}"),
            FetchErr::Other(msg) => write!(f, "{msg}"),
        }
    }
}

fn fetch(agent: &ureq::Agent, url: &str) -> Result<Vec<u8>, FetchErr> {
    let mut response = agent.get(url).call().map_err(|err| match err {
        ureq::Error::StatusCode(code) => FetchErr::Status(code),
        other => FetchErr::Other(other.to_string()),
    })?;
    response
        .body_mut()
        .read_to_vec()
        .map_err(|err| FetchErr::Other(err.to_string()))
}

fn render(icons: &[Icon], svg_dir: &Path, missing: &[String]) -> Result<String, String> {
    let mut body = String::new();
    body.push_str(HEADER);
    body.push_str("//! Generated Fluent System Icons catalogue.\n\n");
    body.push_str("/// One Fluent System Icon from the committed subset.\n");
    body.push_str("#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]\n");
    body.push_str("pub enum Icon {\n");
    for icon in icons {
        body.push_str(&format!("    /// `{0}`.\n    {1},\n", icon.folder, icon.variant));
    }
    body.push_str("}\n\n");
    body.push_str("/// Pixel size of a Fluent System Icon.\n");
    body.push_str("#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]\n");
    body.push_str("pub enum Size {\n    /// 16 px.\n    S16,\n    /// 20 px.\n    S20,\n    /// 24 px.\n    S24,\n}\n\n");
    body.push_str("/// Stroke style of a Fluent System Icon.\n");
    body.push_str("#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]\n");
    body.push_str(
        "pub enum Style {\n    /// Outlined stroke.\n    Regular,\n    /// Solid fill.\n    Filled,\n}\n\n",
    );
    body.push_str(
        "/// SVG bytes for `icon` at `size` and `style`, or `None` when that combo is absent upstream.\n",
    );
    body.push_str("pub fn svg(icon: Icon, size: Size, style: Style) -> Option<&'static [u8]> {\n");
    body.push_str("    Some(match (icon, size, style) {\n");
    for icon in icons {
        for size in SIZES {
            for style in STYLES {
                let key = format!("{}::{size}::{style}", icon.variant);
                if missing.iter().any(|item| item == &key) {
                    let size_v = match size {
                        16 => "S16",
                        20 => "S20",
                        24 => "S24",
                        _ => unreachable!(),
                    };
                    let style_v = match *style {
                        "regular" => "Regular",
                        "filled" => "Filled",
                        _ => unreachable!(),
                    };
                    body.push_str(&format!(
                        "        (Icon::{}, Size::{size_v}, Style::{style_v}) => return None,\n",
                        icon.variant
                    ));
                    continue;
                }
                let file = format!("ic_fluent_{}_{size}_{style}.svg", icon.snake);
                let path = svg_dir.join(&file);
                if !path.is_file() {
                    return Err(format!("missing file {file} (not listed as absent upstream)"));
                }
                let size_v = match size {
                    16 => "S16",
                    20 => "S20",
                    24 => "S24",
                    _ => unreachable!(),
                };
                let style_v = match *style {
                    "regular" => "Regular",
                    "filled" => "Filled",
                    _ => unreachable!(),
                };
                body.push_str(&format!(
                    "        (Icon::{v}, Size::{size_v}, Style::{style_v}) => {{\n            include_bytes!(concat!(\n                env!(\"CARGO_MANIFEST_DIR\"),\n                \"/svg/{file}\"\n            ))\n        }}\n",
                    v = icon.variant
                ));
            }
        }
    }
    body.push_str("    })\n}\n\n");
    body.push_str("/// Size and style combos that do not exist in the pinned upstream revision.\n");
    body.push_str("pub const MISSING: &[(&str, Size, Style)] = &[\n");
    for item in missing {
        let mut parts = item.split("::");
        let variant = parts.next().unwrap_or("");
        let size = parts.next().unwrap_or("");
        let style = parts.next().unwrap_or("");
        let size_v = match size {
            "16" => "S16",
            "20" => "S20",
            "24" => "S24",
            other => return Err(format!("bad size {other}")),
        };
        let style_v = match style {
            "regular" => "Regular",
            "filled" => "Filled",
            other => return Err(format!("bad style {other}")),
        };
        body.push_str(&format!(
            "    (\"{variant}\", Size::{size_v}, Style::{style_v}),\n"
        ));
    }
    if missing.is_empty() {
        // rustfmt collapses an empty list; write it that way so a re-run stays clean.
        let empty = body.rfind("pub const MISSING").ok_or("missing header")?;
        body.truncate(empty);
        body.push_str("pub const MISSING: &[(&str, Size, Style)] = &[];\n\n");
    } else {
        body.push_str("];\n\n");
    }
    body.push_str("impl Icon {\n");
    body.push_str("    /// Every icon in the committed subset, in catalogue order.\n");
    body.push_str("    pub const ALL: &'static [Icon] = &[\n");
    for icon in icons {
        body.push_str(&format!("        Icon::{},\n", icon.variant));
    }
    body.push_str("    ];\n\n");
    body.push_str("    /// The Fluent folder name, for example `Arrow Left`.\n");
    body.push_str("    pub fn name(self) -> &'static str {\n");
    body.push_str("        match self {\n");
    for icon in icons {
        body.push_str(&format!(
            "            Icon::{} => \"{}\",\n",
            icon.variant, icon.folder
        ));
    }
    body.push_str("        }\n    }\n}\n");
    Ok(body)
}

fn pascal(folder: &str) -> String {
    folder
        .split_whitespace()
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

fn snake(folder: &str) -> String {
    folder.to_lowercase().replace(' ', "_")
}

fn rustfmt(path: &Path) -> Result<(), String> {
    let status = std::process::Command::new("rustfmt")
        .arg("--edition")
        .arg("2024")
        .arg(path)
        .status()
        .map_err(|err| format!("rustfmt: {err}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("rustfmt exited with {status}"))
    }
}
